import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.kafka.annotation.KafkaListener;
import org.springframework.mail.SimpleMailMessage;
import org.springframework.mail.javamail.JavaMailSender;
import org.springframework.stereotype.Service;
import com.fasterxml.jackson.databind.ObjectMapper;

@Service
public class SentimentConsumerService {

    @Autowired
    private EmailService emailService;

    @KafkaListener(topics = "weekly-sentiments", groupId = "weekly-sentiment-group")
    public void consume(String message) {
        try {
            SentimentData sentimentData = new ObjectMapper().readValue(message, SentimentData.class);
            if (sentimentData.getEmail() != null && sentimentData.getSentiment() != null) sendEmail(sentimentData);
        } catch (Exception e) {
            org.slf4j.LoggerFactory.getLogger(SentimentConsumerService.class).error("Invalid weekly sentiment message", e);
        }
    }

    private void sendEmail(SentimentData sentimentData) {
        emailService.sendEmail(sentimentData.getEmail(), "Sentiment for previous week", sentimentData.getSentiment());
    }
}
